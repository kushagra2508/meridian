"""Loaders for the on-disk datasets the tools read.

Every file here is a snapshot. `nav_history.json` and `expense_ratios.json` are
regenerated by the scripts in `scripts/`; `products.json` and `tax_rules.json`
are hand-maintained. Keeping them on disk means every tool call is deterministic
and offline.
"""

from __future__ import annotations

import json
from functools import lru_cache
from typing import Any

from .config import (
    EXPENSE_RATIOS_PATH,
    NAV_HISTORY_PATH,
    PRODUCTS_PATH,
    TAX_RULES_PATH,
)


class DatasetMissingError(RuntimeError):
    pass


def _read(path: Any, hint: str) -> dict[str, Any]:
    if not path.exists():
        raise DatasetMissingError(f"{path.name} is missing. {hint}")
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


@lru_cache(maxsize=1)
def nav_history() -> dict[str, Any]:
    return _read(
        NAV_HISTORY_PATH,
        "Regenerate it with `python scripts/pull_nav_history.py`.",
    )


@lru_cache(maxsize=1)
def categories() -> dict[str, dict[str, Any]]:
    return nav_history()["categories"]


@lru_cache(maxsize=1)
def products() -> list[dict[str, Any]]:
    return _read(PRODUCTS_PATH, "It ships with the repository.")["products"]


@lru_cache(maxsize=1)
def tax_rules() -> dict[str, Any]:
    return _read(TAX_RULES_PATH, "It ships with the repository.")


@lru_cache(maxsize=1)
def expense_ratios() -> dict[str, Any]:
    return _read(
        EXPENSE_RATIOS_PATH,
        "Regenerate it with `python scripts/pull_expense_ratios.py`.",
    )


def tax_treatment(category_key: str) -> str:
    """How a nav_history category is taxed: the key into `capital_gains`."""
    table = tax_rules()["category_treatment"]
    if category_key not in table:
        raise KeyError(
            f"No tax treatment recorded for '{category_key}'. Categories with a "
            f"treatment: {', '.join(sorted(table))}."
        )
    return table[category_key]


def category(key: str) -> dict[str, Any]:
    table = categories()
    if key not in table:
        raise KeyError(
            f"Unknown category '{key}'. Known categories: {', '.join(sorted(table))}"
        )
    return table[key]


def forward_returns() -> dict[str, float]:
    """Category key -> haircut-adjusted forward return assumption."""
    return {key: value["assumed_forward_return"] for key, value in categories().items()}


def volatilities() -> dict[str, float]:
    return {key: value["volatility_annualised"] for key, value in categories().items()}


def reset_cache() -> None:
    """Drop memoised datasets. Used by tests that patch the files."""
    for fn in (nav_history, categories, products, tax_rules, expense_ratios):
        fn.cache_clear()
