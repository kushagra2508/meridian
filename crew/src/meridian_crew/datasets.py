"""Loaders for the two on-disk datasets the Feasibility tools read.

Both files are snapshots: `nav_history.json` is regenerated by
`scripts/pull_nav_history.py`, `products.json` is hand-maintained. Keeping them
on disk means every tool call is deterministic and offline.
"""

from __future__ import annotations

import json
from functools import lru_cache
from typing import Any

from .config import NAV_HISTORY_PATH, PRODUCTS_PATH


class DatasetMissingError(RuntimeError):
    pass


def _read(path: Any, hint: str) -> dict[str, Any]:
    if not path.exists():
        raise DatasetMissingError(f"{path.name} is missing. {hint}")
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


@lru_cache(maxsize=1)
def nav_history() -> dict[str, Any]:
    return _read(
        NAV_HISTORY_PATH,
        "Regenerate it with `python scripts/pull_nav_history.py`.",
    )


@lru_cache(maxsize=1)
def categories() -> dict[str, dict[str, Any]]:
    return nav_history()["categories"]


@lru_cache(maxsize=1)
def products() -> list[dict[str, Any]]:
    return _read(PRODUCTS_PATH, "It ships with the repository.")["products"]


def category(key: str) -> dict[str, Any]:
    table = categories()
    if key not in table:
        raise KeyError(
            f"Unknown category '{key}'. Known categories: {', '.join(sorted(table))}"
        )
    return table[key]


def forward_returns() -> dict[str, float]:
    """Category key -> haircut-adjusted forward return assumption."""
    return {key: value["assumed_forward_return"] for key, value in categories().items()}


def volatilities() -> dict[str, float]:
    return {key: value["volatility_annualised"] for key, value in categories().items()}


def reset_cache() -> None:
    """Drop memoised datasets. Used by tests that patch the files."""
    for fn in (nav_history, categories, products):
        fn.cache_clear()
